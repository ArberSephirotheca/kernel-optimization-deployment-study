"""Write the record of reverted performance PRs: RECORDS.md (one section per incident) and reasons.csv
(one row per incident), from catalog.py (which reverts, of which PRs) and records.py (why).

    python3 -I reverted-perf-prs/build.py            # writes both files and prints the summary tables
"""
import csv, json, re, runpy
from collections import Counter, defaultdict
from datetime import datetime
from pathlib import Path

HERE = Path(__file__).resolve().parent
NAMES = {"vllm": "vLLM", "sglang": "SGLang"}
TYPES = {"kernel_optimization": "kernel optimization", "new_kernel_or_fusion": "new kernel, fusion or faster backend",
         "kernel_tuning_config": "kernel tuning config", "precision_format": "low-precision path",
         "system_performance": "system optimization (not a kernel)", "perf_regression_fix": "fix of a performance regression",
         "-": "performance (type not recorded)"}


def pull(repo, n):
    p = HERE / "data" / "raw" / repo / f"pull-{n}.json"
    return json.loads(p.read_text()) if p.exists() else {}


def day(s):
    return datetime.fromisoformat(s.replace("Z", "+00:00")) if s else None


def incidents():
    cat = runpy.run_path(str(HERE / "catalog.py"))["rows"]()
    rec = runpy.run_path(str(HERE / "records.py"))
    by = defaultdict(list)
    for r in cat:
        by[(r["repo"], r["incident"])].append(r)
    out = []
    for key, rs in by.items():
        repo = key[0]
        targets = sorted({int(r["target"]) for r in rs if r["target"] != ""})
        merged = min((pull(repo, n).get("merged_at") or "" for n in targets), default="")
        reverts = sorted({(r["revert_pr"] or r["revert_sha"]): r for r in rs}.values(), key=lambda r: r["revert_date"])
        first = reverts[0]
        rv = pull(repo, first["revert_pr"]) if first["revert_pr"] else {}
        revert_at = rv.get("merged_at") or first["revert_date"]
        days = round((day(revert_at) - day(merged)).total_seconds() / 86400, 2) if merged and revert_at else None
        r = rec["RECORDS"].get(key)
        relands = [(n, (pull(repo, n).get("merged_at") or "")[:10]) for n in (r or {}).get("reland", [])]
        out.append(dict(key=key, repo=repo, targets=targets, title=pull(repo, targets[0]).get("title", first["title"]) if targets else first["title"],
                        merged=merged[:10], reverts=reverts, revert_at=revert_at[:10], days=days,
                        perf_type=first["perf_type"], record=r, relands=relands))
    return sorted(out, key=lambda x: (x["repo"], x["revert_at"])), rec


def section(i):
    r, repo = i["record"], NAMES[i["repo"]]
    prs = ", ".join(f"#{n}" for n in i["targets"]) or "(no PR)"
    lines = [f"### {repo} {prs}: {i['title']}", ""]
    rv = "; ".join(f"#{x['revert_pr'] or x['revert_sha']} ({x['revert_status'].replace('_', ' ')}, {x['revert_date']})"
                   for x in i["reverts"])
    back = ", ".join(f"#{n} ({'merged ' + d if d else 'not merged'})" for n, d in i["relands"]) if i["relands"] else "no"
    if r is None:
        lines += [f"- **Reverted by:** {rv}", "- *No record yet.*", ""]
        return lines
    lines += [f"- **Optimization:** {r['what']} ({TYPES.get(i['perf_type'], i['perf_type'])})",
              f"- **Timeline:** merged {i['merged']}; reverted by {rv}; "
              f"{i['days']} days in main; came back: {back}{' (' + r['reland_kind'] + ')' if i['relands'] else ''}",
              f"- **Failure:** {r['symptom']}{' (silent)' if r['silent'] else ''}; found by {r['found_by']}",
              f"- **Cause:** {r['cause']}, {CAUSES[r['cause']]} (confidence: {r['conf']})"]
    src, quote = r["stated"]
    lines.append(f"- **Stated reason** ({src}): \"{quote}\"" if quote else "- **Stated reason:** none written")
    lines.append(f"- **Reason in detail:** {r['reason']}")
    ev = [f"#{n}" for n in r.get("evidence_prs", [])] + [f"issue #{n}" for n in r.get("evidence_issues", [])]
    if ev:
        lines.append(f"- **Evidence:** {', '.join(ev)}")
    return lines + [""]


def main():
    global CAUSES
    inc, rec = incidents()
    CAUSES = rec["CAUSES"]
    missing = [i["key"] for i in inc if i["record"] is None]
    md = ["# Reverted performance PRs of vLLM and SGLang: the reason of each revert", "",
          "Generated by `build.py` from `catalog.py` and `records.py`; see README.md for the method.", ""]
    for repo in ("vllm", "sglang"):
        rs = [i for i in inc if i["repo"] == repo]
        md += [f"## {NAMES[repo]} ({len(rs)} incidents)", ""]
        for i in rs:
            md += section(i)
    (HERE / "RECORDS.md").write_text("\n".join(md))
    keys = ["repo", "incident", "prs", "title", "perf_type", "merged", "reverts", "revert_date", "days_in_main",
            "revert_kind", "cause", "symptom", "silent", "found_by", "stated_source", "stated", "reason", "reland",
            "reland_kind", "conf"]
    with open(HERE / "reasons.csv", "w", newline="") as f:
        w = csv.DictWriter(f, keys, lineterminator="\n")
        w.writeheader()
        for i in inc:
            r = i["record"] or {}
            w.writerow({"repo": i["repo"], "incident": i["key"][1], "prs": " ".join(f"#{n}" for n in i["targets"]),
                        "title": i["title"], "perf_type": i["perf_type"], "merged": i["merged"],
                        "reverts": " ".join(f"#{x['revert_pr'] or x['revert_sha']}" for x in i["reverts"]),
                        "revert_date": i["revert_at"], "days_in_main": i["days"],
                        "revert_kind": " ".join(sorted({x["revert_status"] for x in i["reverts"]})),
                        "cause": r.get("cause", ""), "symptom": r.get("symptom", ""), "silent": r.get("silent", ""),
                        "found_by": r.get("found_by", ""), "stated_source": (r.get("stated") or ("", ""))[0],
                        "stated": (r.get("stated") or ("", ""))[1], "reason": r.get("reason", ""),
                        "reland": " ".join(f"#{n}" for n in r.get("reland", [])), "reland_kind": r.get("reland_kind", ""),
                        "conf": r.get("conf", "")})
    print(f"{len(inc)} incidents; {len(inc) - len(missing)} with a record; missing: {missing[:8]}{' ...' if len(missing) > 8 else ''}")
    done = [i for i in inc if i["record"]]
    if done:
        summary(done)
        silent(done)


FAMILY = {  # cause -> what kind of reason
    **{c: "a defect of the change" for c in ("PRE", "KERNEL", "LOGIC", "GRAPH", "BUILD", "DEP", "API", "NUM", "MODEL",
                                             "BUDGET", "SKEW")},
    "PERFREG": "not faster, or a wrong measurement", "TEST": "no defect of the change (false alarm or test)",
    "PROC": "no defect of the change (review or design)", "NOTFAIL": "no defect of the change (planned)",
    "UNK": "not known",
}


FINDERS = {  # the finder that the text names first decides the class ("a user report ...; the unit tests had failed")
    "CI or a test after the merge": r"\b(ci|tests?|testing|builds?|nightly)\b",
    "users": r"\busers?\b",
    "maintainers, reviewers or the author": r"\b(maintainers?|reviewers?|authors?|engineers)\b",
    "unknown": r"\bunknown\b",
}


def found_kind(text):
    t = text.lower()
    if "red at the merge" in t or "red before the merge" in t or "cancelled before the merge" in t or "red on the pr" in t:
        return "a check that was red or cancelled before the merge"
    hits = [(m.start(), kind) for kind, rx in FINDERS.items() if (m := re.search(rx, t))]
    return min(hits)[1] if hits else "maintainers, reviewers or the author"


def median(xs):
    xs = sorted(x for x in xs if x is not None)
    return round((xs[(len(xs) - 1) // 2] + xs[len(xs) // 2]) / 2, 1) if xs else None


def summary(done):
    def row(name, rs):
        return (f"| {name} | {sum(i['repo'] == 'vllm' for i in rs)} | {sum(i['repo'] == 'sglang' for i in rs)} | {len(rs)} | "
                f"{sum(bool(i['record']['silent']) for i in rs)} | {median([i['days'] for i in rs])} |")
    print("\n| Cause | vLLM | SGLang | Both | Silent | Median days in main |")
    print("| --- | ---: | ---: | ---: | ---: | ---: |")
    for cause, _ in Counter(i["record"]["cause"] for i in done).most_common():
        print(row(f"{cause}: {CAUSES[cause]}", [i for i in done if i["record"]["cause"] == cause]))
    print("\n| Kind of reason | vLLM | SGLang | Both | Silent | Median days in main |")
    print("| --- | ---: | ---: | ---: | ---: | ---: |")
    for fam, _ in Counter(FAMILY[i["record"]["cause"]] for i in done).most_common():
        print(row(fam, [i for i in done if FAMILY[i["record"]["cause"]] == fam]))
    print("\n| Symptom | Incidents | Silent |")
    print("| --- | ---: | ---: |")
    for s, n in Counter(i["record"]["symptom"] for i in done).most_common():
        print(f"| {s} | {n} | {sum(1 for i in done if i['record']['symptom'] == s and i['record']['silent'])} |")
    print("\n| Found by | vLLM | SGLang | Both |")
    print("| --- | ---: | ---: | ---: |")
    for k, n in Counter(found_kind(i["record"]["found_by"]) for i in done).most_common():
        rs = [i for i in done if found_kind(i["record"]["found_by"]) == k]
        print(f"| {k} | {sum(i['repo'] == 'vllm' for i in rs)} | {sum(i['repo'] == 'sglang' for i in rs)} | {n} |")
    back = [i for i in done if i["relands"]]
    gaps = []
    for i in back:
        ds = [d for _, d in i["relands"] if d]
        if ds and i["revert_at"]:
            gaps.append((day(min(ds) + "T00:00:00Z") - day(i["revert_at"] + "T00:00:00Z")).days)
    print(f"\ndays in main: median {median([i['days'] for i in done])}, silent {median([i['days'] for i in done if i['record']['silent']])}, "
          f"loud {median([i['days'] for i in done if not i['record']['silent']])}; sum {round(sum(i['days'] or 0 for i in done))}")
    print(f"came back: {len(back)} of {len(done)} (vLLM {sum(i['repo'] == 'vllm' for i in back)}, SGLang "
          f"{sum(i['repo'] == 'sglang' for i in back)}); median days from the revert to the reland {median(gaps)}")
    print("reland kinds:", dict(Counter(i["record"]["reland_kind"] for i in done)))
    print("confidence:", dict(Counter(i["record"]["conf"] for i in done)))
    print("stated reason written:", sum(bool(i["record"]["stated"][1]) for i in done), "of", len(done),
          "| stated in the revert itself:", sum(i["record"]["stated"][0].startswith(("revert", "rollback", "partial revert"))
                                                 for i in done))


def silent(done):
    """The tables and the numbers of the README section "Silent failures", from silent.py."""
    sil = runpy.run_path(str(HERE / "silent.py"))
    groups, notes, ci = sil["GROUPS"], sil["NOTES"], "CI or a test after the merge"
    S = [i for i in done if i["record"]["silent"]]
    assert {i["key"] for i in S} == set(notes), "silent.py needs one note for each silent incident, and no other"
    by = defaultdict(list)
    for i in S:
        by[groups[i["record"]["cause"]]].append(i)
    order = [g for g in dict.fromkeys(groups.values()) if by[g]]

    def cells(rs):
        k = [found_kind(i["record"]["found_by"]) for i in rs]
        return (f"{len(rs)} | {sum(i['days'] for i in rs):.1f} | {median([i['days'] for i in rs])} | "
                f"{k.count('users')} | {k.count(ci)}")
    print("\n| Group | Incidents | Days in main (sum) | Median days | Found by users | Found by a CI test after the merge "
          "| What can find it before the merge (assessment) |")
    print("| --- | ---: | ---: | ---: | ---: | ---: | --- |")
    for g in order:
        print(f"| {g} | {cells(by[g])} | {sil['CHECKS'][g]} |")
    print(f"| all | {cells(S)} | |")
    print("\n| Incident | Optimization | What went wrong | Days | Found by | Before the merge (assessment) |")
    print("| --- | --- | --- | ---: | --- | --- |")
    for g in order:
        print(f"| **{g}** | | | | | |")
        for i in sorted(by[g], key=lambda i: -i["days"]):
            opt, wrong, found, check, _ = notes[i["key"]]
            prs = ", ".join(f"#{n}" for n in i["targets"])
            print(f"| {NAMES[i['repo']]} {prs} | {opt} | {wrong} | {i['days']:.1f} | {found} | {check} |")
    tot, days = sum(i["days"] or 0 for i in done), sum(i["days"] for i in S)
    print(f"\nsilent: {len(S)} of {len(done)};",
          ", ".join(f"{NAMES[r]} {sum(i['repo'] == r for i in S)} of {sum(i['repo'] == r for i in done)}" for r in NAMES),
          f"| days in main {days:.1f} of {tot:.1f} ({100 * days / tot:.0f}%)")
    print(f"more than 5 days in main: silent {sum(i['days'] > 5 for i in S)} of {len(S)}, the others "
          f"{sum((i['days'] or 0) > 5 for i in done if not i['record']['silent'])} of {len(done) - len(S)}")
    defects = sorted((i for i in done if FAMILY[i["record"]["cause"]] in ("a defect of the change", "not known")),
                     key=lambda i: -(i["days"] or 0))
    print("longest-staying defects:", ", ".join(f"{i['key'][1]} {i['days']:.1f}{' silent' if i['record']['silent'] else ''}"
                                                for i in defects[:8]))
    for k in (ci, "users", "maintainers, reviewers or the author", "unknown"):
        ds = [i["days"] for i in S if found_kind(i["record"]["found_by"]) == k]
        print(f"found by {k}: {len(ds)}, median {median(ds)} days")
    print("perf types:", dict(Counter(i["perf_type"] for i in S)))
    print(f"came back: {sum(bool(i['relands']) for i in S)};", dict(Counter(i["record"]["reland_kind"] for i in S)))
    formal = {k for k in notes if notes[k][4]}
    after = {i["key"] for i in S if found_kind(i["record"]["found_by"]) == ci}
    rest = sorted(k[1] for k in set(notes) - formal - after)
    print(f"formal checks target {len(formal)}: {dict(sorted(Counter(notes[k][4].rstrip('?') for k in formal).items()))}, "
          f"{sum(notes[k][4].endswith('?') for k in formal)} probable; a CI test after the merge found {len(after)}; "
          f"together {len(formal | after)}; the other {len(rest)}: {', '.join(rest)}")


if __name__ == "__main__":
    main()
